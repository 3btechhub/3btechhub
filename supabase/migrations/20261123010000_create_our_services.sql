create table public.our_services (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(btrim(title)) between 1 and 120),
  description text not null default '' check (char_length(description) <= 600),
  sort_order integer not null default 0,
  is_visible boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.our_services enable row level security;

revoke all on table public.our_services from public, anon, authenticated;
grant select on table public.our_services to anon, authenticated;
grant insert, update, delete on table public.our_services to authenticated;
grant usage, select on sequence public.our_services_id_seq to authenticated;

create policy "Public can read visible services"
on public.our_services
for select
to anon, authenticated
using (is_visible = true or (select auth.jwt() -> 'app_metadata' ->> 'role') = 'Owner');

create policy "Owner can insert services"
on public.our_services
for insert
to authenticated
with check ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'Owner');

create policy "Owner can update services"
on public.our_services
for update
to authenticated
using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'Owner')
with check ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'Owner');

create policy "Owner can delete services"
on public.our_services
for delete
to authenticated
using ((select auth.jwt() -> 'app_metadata' ->> 'role') = 'Owner');
